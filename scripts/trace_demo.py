#!/usr/bin/env python3
"""Print Soar's own decision-cycle trace for a short trip.

    python scripts/trace_demo.py            # writes results/sample_trace.txt

The text is produced by the Soar kernel (`trace 1`): it shows operators
being selected, the impasses (==>S: S2 ...) and the chunks being built.
Nothing in the trace is generated by Python.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from cognav.scenarios import Scenario  # noqa: E402
from cognav.simulation import run_episode  # noqa: E402
from cognav.soar_agent import SoarNavigator  # noqa: E402


def main() -> None:
    # corridor (5,6) -> lower level (9,9): short, but needs one plan-route
    # subgoal and runs into a tie between two equally cheap moves.
    sc = Scenario(name="trace-demo", title="trace demo", map="maps/campus_floor.txt",
                  profile="standard", start=(9, 6), goal=(14, 9))
    nav = SoarNavigator()
    chunks: list[str] = []
    nav.capture_trace(chunks.append, level=1)
    res = run_episode(nav, sc)
    text = "".join(chunks)
    text += ("\n\n--- working memory: top state (print --depth 2 S1) ---\n"
             + nav.cli("print --depth 2 S1")
             + "\n--- chunks learned (print --chunks --full) ---\n"
             + nav.cli("print --chunks --full")
             + "\n--- stats ---\n" + nav.cli("stats"))
    out = ROOT / "results" / "sample_trace.txt"
    out.parent.mkdir(exist_ok=True)
    out.write_text(text)
    print(text)
    print(f"\n[{res.outcome}: {res.steps} steps, {res.decisions} decisions] -> {out}")


if __name__ == "__main__":
    main()
